-- Sistema de Consulta Histórica y Gestión de Facturación GobreeBelt
-- Ejecutar en Supabase SQL editor o mediante Supabase CLI.

create extension if not exists pg_trgm;
create extension if not exists unaccent;

create table if not exists public.clientes (
  id uuid primary key default gen_random_uuid(),
  nombre text not null,
  rfc varchar(20),
  direccion text,
  telefono varchar(60),
  email varchar(180),
  contacto_principal varchar(180),
  notas text,
  created_at timestamptz not null default now()
);

create table if not exists public.facturas (
  id uuid primary key default gen_random_uuid(),
  folio varchar(80) not null,
  fecha date not null,
  cliente_id uuid not null references public.clientes(id) on delete restrict,
  oc varchar(120),
  codigo_interno varchar(120),
  subtotal numeric(14,2),
  iva numeric(14,2),
  total numeric(14,2),
  observaciones text,
  estatus varchar(20) not null default 'Pendiente' check (estatus in ('Pendiente', 'Validada', 'Archivada')),
  pdf_url text,
  xml_url text,
  imagen_url text,
  fts tsvector generated always as (
    setweight(to_tsvector('spanish', coalesce(observaciones, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(folio, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(oc, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(codigo_interno, '')), 'B')
  ) stored,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (cliente_id, folio)
);

create table if not exists public.partidas (
  id uuid primary key default gen_random_uuid(),
  factura_id uuid not null references public.facturas(id) on delete cascade,
  descripcion text,
  tipo_banda varchar(180),
  ancho_mm numeric(12,2),
  longitud_mm numeric(12,2),
  medidas_internas varchar(180),
  guia varchar(180),
  tipo_union varchar(180),
  cantidad numeric(12,2) not null default 1,
  precio_unitario numeric(14,2),
  importe numeric(14,2),
  fts tsvector generated always as (
    setweight(to_tsvector('spanish', coalesce(descripcion, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(tipo_banda, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(medidas_internas, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(guia, '')), 'C')
  ) stored
);

create table if not exists public.documentos_factura (
  id uuid primary key default gen_random_uuid(),
  factura_id uuid not null references public.facturas(id) on delete cascade,
  tipo varchar(20) not null check (tipo in ('pdf', 'xml', 'imagen')),
  nombre_archivo text not null,
  bucket text not null,
  storage_path text not null,
  url text not null,
  usuario_carga text,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  usuario text,
  rol varchar(40),
  accion varchar(80) not null,
  tabla varchar(80) not null,
  registro_id text,
  cambios jsonb not null default '{}'::jsonb,
  fecha timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_facturas_updated_at on public.facturas;
create trigger trg_facturas_updated_at before update on public.facturas
for each row execute function public.set_updated_at();

