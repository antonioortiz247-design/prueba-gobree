-- Búsqueda global priorizando observaciones/descripción y cubriendo cliente/RFC/datos técnicos.
create or replace view public.v_facturas_busqueda as
select
  f.*,
  c.nombre as cliente_nombre,
  c.rfc,
  p.descripcion,
  p.tipo_banda,
  p.ancho_mm,
  p.longitud_mm,
  p.medidas_internas,
  p.guia,
  (
    setweight(to_tsvector('spanish', coalesce(f.observaciones, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(p.descripcion, '')), 'A') ||
    setweight(to_tsvector('spanish', coalesce(c.nombre, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(c.rfc, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(f.folio, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(f.oc, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(f.codigo_interno, '')), 'B') ||
    setweight(to_tsvector('spanish', coalesce(p.tipo_banda, '')), 'C') ||
    setweight(to_tsvector('spanish', coalesce(p.medidas_internas, '')), 'C') ||
    setweight(to_tsvector('spanish', coalesce(p.guia, '')), 'C')
  ) as search_vector
from public.facturas f
join public.clientes c on c.id = f.cliente_id
left join public.partidas p on p.factura_id = f.id;


-- RPC usada por /api/facturas para que la búsqueda global y los filtros técnicos
-- se ejecuten en PostgreSQL con paginación antes de cargar el detalle anidado.
create or replace function public.buscar_facturas_ids(
  p_q text default null,
  p_cliente text default null,
  p_rfc text default null,
  p_folio text default null,
  p_oc text default null,
  p_codigo_interno text default null,
  p_fecha_inicial date default null,
  p_fecha_final date default null,
  p_ancho_mm numeric default null,
  p_longitud_mm numeric default null,
  p_medidas_internas text default null,
  p_tipo_banda text default null,
  p_guia text default null,
  p_observaciones text default null,
  p_monto_minimo numeric default null,
  p_monto_maximo numeric default null,
  p_estatus text default null,
  p_limit integer default 25,
  p_offset integer default 0
)
returns table(id uuid, fecha date, total_count bigint)
language sql
stable
as $$
with query_values as (
  select
    nullif(trim(p_q), '') as q,
    case when nullif(trim(p_q), '') is null then null else plainto_tsquery('spanish', nullif(trim(p_q), '')) end as tsq
), matched as (
  select f.id, f.fecha
  from public.facturas f
  join public.clientes c on c.id = f.cliente_id
  cross join query_values qv
  where
    (p_folio is null or f.folio ilike '%' || p_folio || '%') and
    (p_oc is null or f.oc ilike '%' || p_oc || '%') and
    (p_codigo_interno is null or f.codigo_interno ilike '%' || p_codigo_interno || '%') and
    (p_estatus is null or f.estatus ilike '%' || p_estatus || '%') and
    (p_cliente is null or c.nombre ilike '%' || p_cliente || '%' or c.rfc ilike '%' || p_cliente || '%') and
    (p_rfc is null or c.rfc ilike '%' || p_rfc || '%') and
    (p_fecha_inicial is null or f.fecha >= p_fecha_inicial) and
    (p_fecha_final is null or f.fecha <= p_fecha_final) and
    (p_monto_minimo is null or f.total >= p_monto_minimo) and
    (p_monto_maximo is null or f.total <= p_monto_maximo) and
    (p_observaciones is null or f.observaciones ilike '%' || p_observaciones || '%') and
    (
      qv.q is null or
      f.fts @@ qv.tsq or
      c.nombre ilike '%' || qv.q || '%' or
      c.rfc ilike '%' || qv.q || '%' or
      exists (select 1 from public.partidas p where p.factura_id = f.id and p.fts @@ qv.tsq) or
      exists (
        select 1 from public.partidas p
        where p.factura_id = f.id and (
          p.descripcion ilike '%' || qv.q || '%' or
          p.tipo_banda ilike '%' || qv.q || '%' or
          p.medidas_internas ilike '%' || qv.q || '%' or
          p.guia ilike '%' || qv.q || '%'
        )
      )
    ) and
    (p_ancho_mm is null or exists (select 1 from public.partidas p where p.factura_id = f.id and p.ancho_mm = p_ancho_mm)) and
    (p_longitud_mm is null or exists (select 1 from public.partidas p where p.factura_id = f.id and p.longitud_mm = p_longitud_mm)) and
    (p_medidas_internas is null or exists (select 1 from public.partidas p where p.factura_id = f.id and p.medidas_internas ilike '%' || p_medidas_internas || '%')) and
    (p_tipo_banda is null or exists (select 1 from public.partidas p where p.factura_id = f.id and p.tipo_banda ilike '%' || p_tipo_banda || '%')) and
    (p_guia is null or exists (select 1 from public.partidas p where p.factura_id = f.id and p.guia ilike '%' || p_guia || '%'))
), counted as (
  select count(*) as total_count from matched
)
select m.id, m.fecha, c.total_count
from matched m
cross join counted c
order by m.fecha desc, m.id desc
limit greatest(1, least(coalesce(p_limit, 25), 100))
offset greatest(0, coalesce(p_offset, 0));
$$;

create or replace view public.v_facturacion_dashboard as
select
  (select count(*) from public.facturas) as facturas_registradas,
  (select count(*) from public.clientes) as clientes_registrados,
  (select count(*) from public.facturas where date_part('year', fecha) = date_part('year', current_date)) as facturas_este_anio,
  (select coalesce(sum(total), 0) from public.facturas where date_part('year', fecha) = date_part('year', current_date)) as ventas_este_anio,
  (select count(*) from public.facturas where date_trunc('month', fecha) = date_trunc('month', current_date)) as facturas_este_mes,
  (select coalesce(sum(total), 0) from public.facturas where date_trunc('month', fecha) = date_trunc('month', current_date)) as ventas_este_mes;

create or replace view public.v_clientes_frecuentes as
select c.id, c.nombre, c.rfc, count(f.id) as facturas, coalesce(sum(f.total),0) as total_comprado
from public.clientes c join public.facturas f on f.cliente_id = c.id
group by c.id, c.nombre, c.rfc order by facturas desc, total_comprado desc;

create or replace view public.v_medidas_mas_vendidas as
select ancho_mm, longitud_mm, medidas_internas, count(*) as partidas, coalesce(sum(cantidad),0) as cantidad
from public.partidas group by ancho_mm, longitud_mm, medidas_internas order by partidas desc;

create or replace view public.v_bandas_mas_vendidas as
select tipo_banda, count(*) as partidas, coalesce(sum(cantidad),0) as cantidad, coalesce(sum(importe),0) as importe
from public.partidas where tipo_banda is not null and tipo_banda <> '' group by tipo_banda order by partidas desc;

create or replace view public.v_ventas_por_anio as
select date_part('year', fecha)::int as anio, count(*) as facturas, coalesce(sum(total),0) as total
from public.facturas group by anio order by anio desc;

create or replace view public.v_ventas_por_mes as
select to_char(date_trunc('month', fecha), 'YYYY-MM') as mes, count(*) as facturas, coalesce(sum(total),0) as total
from public.facturas group by mes order by mes desc;

create or replace view public.v_ventas_por_cliente as
select c.id, c.nombre, c.rfc, coalesce(sum(f.total),0) as total
from public.clientes c join public.facturas f on f.cliente_id = c.id group by c.id, c.nombre, c.rfc order by total desc;

create or replace view public.v_facturas_por_cliente as
select c.id, c.nombre, c.rfc, count(f.id) as facturas
from public.clientes c left join public.facturas f on f.cliente_id = c.id group by c.id, c.nombre, c.rfc order by facturas desc;

create or replace view public.v_facturas_por_usuario as
select usuario, count(*) filter (where accion in ('crear','importar_xml')) as facturas_capturadas
from public.audit_logs group by usuario order by facturas_capturadas desc;

